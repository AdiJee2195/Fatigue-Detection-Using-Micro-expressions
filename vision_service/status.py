"""Explicit provenance for every signal in a telemetry row.

The UI must be able to tell a real measurement from a synthetic one, and a real
detection from a fallback crop. Without this vocabulary the only options are
"a number" or "no number", and a demo-mode value becomes indistinguishable from
a live one — which is exactly the failure this project cannot afford.

Every value here is rendered verbatim by the dashboard.
"""
from __future__ import annotations

from enum import Enum


class SignalStatus(str, Enum):
    """How a value was obtained (or why it is absent)."""

    #: Measured from this frame by a real algorithm.
    LIVE = "live"
    #: Generated by the deterministic stub. Demo mode only; never a measurement.
    SYNTHETIC = "synthetic"
    #: Produced by a fallback heuristic rather than a real measurement.
    ESTIMATED = "estimated"
    #: The capability is not wired up in this deployment at all.
    UNAVAILABLE = "unavailable"
    #: The capability exists but produced nothing for this frame.
    NOT_DETECTED = "not_detected"
    #: No implementation is configured (e.g. no FACS model, no rPPG provider).
    NOT_CONFIGURED = "not_configured"


class FaceSource(str, Enum):
    """Where the face crop came from.

    ``CENTRE_CROP`` is deliberately distinct from the detectors: a centre crop is
    not a face detection, and telemetry derived from it must say so.
    """

    MEDIAPIPE = "mediapipe"
    OPENCV = "opencv"
    CENTRE_CROP = "centre_crop"
    #: No frame was inspected at all: the row was generated by the stub generator.
    SYNTHETIC = "synthetic"
    NONE = "none"


#: Sources that represent an actual detection.
DETECTING_SOURCES = frozenset({FaceSource.MEDIAPIPE, FaceSource.OPENCV})
