/**
 * Why the current assessment is what it is.
 *
 * Every sentence in this panel is produced by the deterministic rule engine and
 * arrives in `assessment.findings[].plain`. The frontend never authors an
 * explanation, never paraphrases one, and never fills a gap with plausible text —
 * if the engine reported no findings, this panel says so.
 */
import { Badge, Panel } from './primitives';
import { formatPercent } from '../lib/format';
import type { Assessment, Finding } from '../types';

export interface ExplainabilityPanelProps {
  assessment: Assessment | null;
}

function severityTone(severity: number): 'neutral' | 'info' | 'warn' | 'error' {
  if (severity >= 3) return 'error';
  if (severity === 2) return 'warn';
  if (severity === 1) return 'info';
  return 'neutral';
}

function severityLabel(severity: number): string {
  if (severity >= 3) return 'strong';
  if (severity === 2) return 'moderate';
  if (severity === 1) return 'mild';
  return 'info';
}

function FindingRow({ finding }: { finding: Finding }) {
  return (
    <li className="border-l-2 border-slate-700 pl-3">
      <div className="flex flex-wrap items-center gap-2">
        <span className="font-mono text-xs text-slate-500">{finding.id}</span>
        <Badge tone={severityTone(finding.severity)}>{severityLabel(finding.severity)}</Badge>
        {finding.pre_attentive ? (
          <Badge tone="warn" title="Present before the classifier probability rises">
            pre-attentive
          </Badge>
        ) : null}
      </div>
      <p className="mt-1 text-sm text-slate-200">{finding.plain}</p>
    </li>
  );
}

export function ExplainabilityPanel({ assessment }: ExplainabilityPanelProps) {
  const findings = assessment?.findings ?? [];

  return (
    <Panel
      title="Why this assessment"
      aside={
        assessment ? (
          <Badge tone={findings.length > 0 ? 'info' : 'neutral'}>
            {findings.length} finding{findings.length === 1 ? '' : 's'}
          </Badge>
        ) : (
          <Badge tone="neutral">awaiting engine</Badge>
        )
      }
    >
      {!assessment ? (
        <p className="text-sm text-slate-400">
          The explanation engine has not reported yet. Assessments arrive roughly every two
          seconds while frames are streaming.
        </p>
      ) : (
        <>
          <p className="mb-3 text-sm text-slate-300">
            <span className="font-semibold text-slate-100">
              Why is risk {assessment.risk_level ?? 'UNKNOWN'}?
            </span>{' '}
            {findings.length === 0
              ? 'The rule engine reported no active findings for this window.'
              : `${findings.length} rule${findings.length === 1 ? '' : 's'} fired over the recent observation window.`}
            {typeof assessment.p_fatigue_smoothed === 'number' ? (
              <span className="text-slate-400">
                {' '}
                Smoothed fatigue probability {formatPercent(assessment.p_fatigue_smoothed, 1)}.
              </span>
            ) : null}
          </p>

          {findings.length > 0 ? (
            <ul className="space-y-3">
              {findings.map((finding) => (
                <FindingRow key={`${finding.id}-${finding.plain}`} finding={finding} />
              ))}
            </ul>
          ) : null}

          <p className="mt-4 text-xs text-slate-500">
            Explanations are generated by deterministic rules from the telemetry above. Where
            language-model phrasing is used, it is validated against those rules and replaced
            by a template if it disagrees with them.
          </p>
        </>
      )}
    </Panel>
  );
}
